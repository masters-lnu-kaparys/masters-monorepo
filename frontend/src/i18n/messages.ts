const dictionaries = { uk, en } satisfies Record<AppLanguage, TranslationDictionary>;

function interpolate(template: string, params?: TranslationParams): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));
}

export function translate(language: AppLanguage, key: string, params?: TranslationParams): string {
  const dictionary = dictionaries[language] ?? dictionaries.uk;
  const fallback = dictionaries.uk;
  const template = dictionary[key] ?? fallback[key] ?? key;
  return interpolate(template, params);
}
